#!/usr/bin/env python3
"""Regenerates src/test_images.h: images signed with throwaway keys, so that the
suite needs no Python packages at build time and no key from outside. Run with the
NCS toolchain's python3 on PATH, like scripts/sign-llext.py, and commit the result.
"""
import os
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SIGN = HERE.parents[2] / "scripts/sign-llext.py"
IMGTOOL = os.environ.get("IMGTOOL", "/opt/nordic/ncs/v3.2.0/bootloader/mcuboot/scripts/imgtool.py")
FIRMWARE_ID = 0x12345678


def run(*args):
    subprocess.run([sys.executable, *map(str, args)], check=True, stdout=subprocess.DEVNULL)


def c_array(name, data):
    rows = ",\n".join(
        "    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) for i in range(0, len(data), 12)
    )
    return f"inline constexpr uint8_t {name}[{len(data)}] = {{\n{rows}\n}};\n"


def public_key(tmp, name):
    key, pem, header = tmp / f"{name}.pem", tmp / f"{name}.pub.pem", tmp / f"{name}.h"
    run(SIGN, "keygen", "--key", key, "--pubkey", pem)
    run(SIGN, "header", pem, header)
    body = header.read_text().split("{", 1)[1].split("}", 1)[0]
    return key, bytes(int(value, 16) for value in body.replace(",", " ").split())


def main():
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        key, signing_public = public_key(tmp, "signing")
        _, other_public = public_key(tmp, "other")

        # Only signed here, not loaded, so it needn't be more of an ELF than this.
        elf = tmp / "payload.llext"
        elf.write_bytes(b"\x7fELF" + bytes(i & 0xFF for i in range(124)))

        signed = tmp / "signed.bin"
        run(SIGN, "sign", elf, "--firmware-id", hex(FIRMWARE_ID), "--key", key, "-o", signed)

        # What a signer that isn't sign-llext.py could produce: no firmware ID.
        no_id = tmp / "no_id.bin"
        run(IMGTOOL, "sign", "-k", key, "--version", "0.0.0+0", "--header-size", "0x20", "--pad-header",
            "--overwrite-only", "--slot-size", "0x2000", "--align", "4", elf, no_id)

        (HERE / "src/test_images.h").write_text(
            "/* Generated by ../generate_test_images.py. */\n"
            "#pragma once\n\n"
            "#include <cstdint>\n\n"
            f"inline constexpr uint32_t kFirmwareId = 0x{FIRMWARE_ID:08x};\n\n"
            + c_array("kSigningKey", signing_public) + "\n"
            + c_array("kOtherKey", other_public) + "\n"
            + c_array("kPayload", elf.read_bytes()) + "\n"
            + c_array("kSignedImage", signed.read_bytes()) + "\n"
            + c_array("kNoFirmwareIdImage", no_id.read_bytes())
        )


if __name__ == "__main__":
    main()
