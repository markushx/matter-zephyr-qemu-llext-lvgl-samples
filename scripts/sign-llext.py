#!/usr/bin/env python3
"""Sign an LLEXT (.llext) binary for the 6_nrf52840_signed/ sample, with MCUboot's
imgtool as the signing tool. The result is an ordinary imgtool image: a 32-byte
header, the unchanged ELF, and TLVs holding the ECDSA P-256 signature. It is sent
like any other extension, with scripts/send-llext.py.

The signature also covers the ID of the firmware the extension is for, so it is
only accepted there. That makes reflashing the way to revoke every signature so far.

    keygen    creates the private key and writes the public key the firmware embeds
    sign      signs an extension for one firmware build
    header    turns the public key into a C header; the firmware build runs this

Needs imgtool's Python packages, so run keygen and sign with the NCS toolchain's
python3 on PATH (see README.md). header only needs the standard library.

Usage:
    scripts/sign-llext.py keygen [--key FILE] [--pubkey FILE]
    scripts/sign-llext.py sign <in.llext> --firmware <zephyr.bin> [--key FILE] [-o FILE]
    scripts/sign-llext.py header <public.pem> <out.h>
"""
import argparse
import base64
import os
import pathlib
import stat
import subprocess
import sys
import zlib

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_KEY = pathlib.Path.home() / ".config/matter-zephyr-qemu/extension-signing.pem"
DEFAULT_PUBKEY = REPO_ROOT / "6_nrf52840_signed/keys/extension-signing.pub.pem"
DEFAULT_IMGTOOL = "/opt/nordic/ncs/v3.2.0/bootloader/mcuboot/scripts/imgtool.py"

# Must match ExtensionSignature.cpp and ExtensionStore::kSlotSize.
FIRMWARE_ID_TLV = 0xA0
HEADER_SIZE = 0x20
SLOT_SIZE = 0x2000
# Everything of a P-256 SubjectPublicKeyInfo but the point itself.
P256_SPKI_PREFIX = bytes.fromhex("3059301306072a8648ce3d020106082a8648ce3d030107034200")
P256_POINT_SIZE = 65


def imgtool(*args):
    tool = os.environ.get("IMGTOOL", DEFAULT_IMGTOOL)
    result = subprocess.run([sys.executable, tool, *map(str, args)], capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"imgtool {args[0]} failed:\n{result.stdout}{result.stderr}")
    return result.stdout


def keygen(args):
    # Overwriting a key would make everything signed with it useless.
    if args.key.exists():
        sys.exit(f"{args.key} already exists, not overwriting it")
    args.key.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    imgtool("keygen", "-k", args.key, "-t", "ecdsa-p256")
    args.key.chmod(stat.S_IRUSR | stat.S_IWUSR)
    imgtool("getpub", "-k", args.key, "-e", "pem", "-o", args.pubkey)
    print(f"Private key: {args.key} (keep it out of the repository)")
    print(f"Public key:  {args.pubkey} (rebuild the firmware to embed it)")


def sign(args):
    if args.input.read_bytes()[:4] != b"\x7fELF":
        sys.exit(f"{args.input} is not an ELF file: is it signed already?")
    if not args.key.exists():
        sys.exit(f"{args.key} doesn't exist: run keygen first, or pass --key")

    if args.firmware_id is not None:
        firmware_id = int(args.firmware_id, 0)
    else:
        # What ExtensionStore::FirmwareId() computes on the device.
        firmware_id = zlib.crc32(args.firmware.read_bytes())

    output = args.output or args.input.with_suffix(".signed" + args.input.suffix)
    imgtool(
        "sign",
        "-k", args.key,
        "--version", args.version,
        "--header-size", hex(HEADER_SIZE),
        "--pad-header",
        # The image isn't for MCUboot: this only leaves out the swap trailer's
        # space from the size check.
        "--overwrite-only",
        "--slot-size", hex(SLOT_SIZE),
        "--align", "4",
        "--custom-tlv", hex(FIRMWARE_ID_TLV), "0x" + firmware_id.to_bytes(4, "little").hex(),
        args.input,
        output,
    )
    imgtool("verify", "-k", args.key, output)
    print(f"{output}: {output.stat().st_size} bytes, for firmware 0x{firmware_id:08x}")


def header(args):
    pem = [line.strip() for line in args.pubkey.read_text().splitlines()]
    if "-----BEGIN PUBLIC KEY-----" not in pem or "-----END PUBLIC KEY-----" not in pem:
        sys.exit(f"{args.pubkey} is not a PEM public key")
    der = base64.b64decode("".join(line for line in pem if not line.startswith("-----")))
    point = der[len(P256_SPKI_PREFIX) :]
    if not der.startswith(P256_SPKI_PREFIX) or len(point) != P256_POINT_SIZE or point[0] != 0x04:
        sys.exit(f"{args.pubkey} is not an uncompressed P-256 public key")

    array = ",\n".join(
        "    " + ", ".join(f"0x{b:02x}" for b in point[i : i + 12]) for i in range(0, len(point), 12)
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        f"/* Generated by scripts/sign-llext.py from {args.pubkey.name}. */\n"
        "#pragma once\n\n"
        "#include <cstdint>\n\n"
        f"inline constexpr uint8_t kExtensionSigningPublicKey[{P256_POINT_SIZE}] = {{\n{array}\n}};\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    p = commands.add_parser("keygen", help="create the signing key")
    p.add_argument("--key", type=pathlib.Path, default=DEFAULT_KEY)
    p.add_argument("--pubkey", type=pathlib.Path, default=DEFAULT_PUBKEY)
    p.set_defaults(func=keygen)

    p = commands.add_parser("sign", help="sign an extension")
    p.add_argument("input", type=pathlib.Path)
    target = p.add_mutually_exclusive_group(required=True)
    target.add_argument("--firmware", type=pathlib.Path, help="the build's zephyr/zephyr.bin")
    target.add_argument("--firmware-id", help="the firmware ID itself, for tests")
    p.add_argument("--key", type=pathlib.Path, default=DEFAULT_KEY)
    p.add_argument("--version", default="0.0.0+0", help="stored in the image; the device doesn't check it")
    p.add_argument("-o", "--output", type=pathlib.Path, help="default <in>.signed.llext")
    p.set_defaults(func=sign)

    p = commands.add_parser("header", help="write the public key as a C header")
    p.add_argument("pubkey", type=pathlib.Path)
    p.add_argument("output", type=pathlib.Path)
    p.set_defaults(func=header)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
